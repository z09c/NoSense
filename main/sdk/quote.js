function pickPool() {
  var i = Math.floor(Math.random() * POOL.length);
  return { text: POOL[i], from: '预装名句池', fromWho: '', cat: 'pool' };
}

function fetch(cb) {
  var url = 'https://v1.hitokoto.cn/?c=i&c=k&c=d&c=h&encode=json';
  net.getJson(url, { timeout: 8000 }, function (err, json) {
    if (err || !json || typeof json.hitokoto !== 'string') {
      return cb(null, pickPool(), err ? 'hitokoto 失败(' + err.message + ')，使用本地名句池' : 'hitokoto 结构异常，使用本地名句池');
    }
    cb(null, {
      text: json.hitokoto.replace(/\s+$/, ''),
      from: json.from || '',
      fromWho: json.from_who || '',
      cat: json.type || ''
    });
  });
}

